// Dictionnaires par domaine (page) — fusionnés ici pour que chaque domaine
// puisse être traduit dans son propre fichier sans toucher au cœur.
const DOMAIN_DICTS = [
  aboutDict,
  settingsDict,
  defisDict,
  tournoisDict,
  miscDict,
  leaderboardDict,
  profilDict,
  pagesDict,
  histteamDict,
  economyDict,
  battlepassDict,
];

const DICTS: Record<Lang, Dict> = {
  fr: Object.assign({}, fr, ...DOMAIN_DICTS.map((d) => d.fr)),
  en: Object.assign({}, en, ...DOMAIN_DICTS.map((d) => d.en)),
  es: Object.assign({}, es, ...DOMAIN_DICTS.map((d) => d.es)),
  // Domaines désormais traduits dans les 6 langues (ja/ar/pt inclus) — fusion
  // complète ; le fallback t() (→ en → fr) ne sert plus que de filet de sécurité.
  ja: Object.assign({}, ja, ...DOMAIN_DICTS.map((d) => d.ja)),
  ar: Object.assign({}, ar, ...DOMAIN_DICTS.map((d) => d.ar)),
  pt: Object.assign({}, pt, ...DOMAIN_DICTS.map((d) => d.pt)),
};
const LOCALES: Record<Lang, string> = {
  fr: 'fr-FR', en: 'en-GB', es: 'es-ES', ja: 'ja-JP', ar: 'ar', pt: 'pt-BR',
};

function readInitialLang(): Lang {
  const stored = getStoredLang();
  if (
    stored === 'fr' || stored === 'en' || stored === 'es' ||
    stored === 'ja' || stored === 'ar' || stored === 'pt'
  ) {
    return stored;
  }
  // Détection navigateur.
  if (typeof navigator !== 'undefined') {
    const nav = navigator.language.toLowerCase();
    if (nav.startsWith('ja')) return 'ja';
    if (nav.startsWith('ar')) return 'ar';
    if (nav.startsWith('pt')) return 'pt';
    if (nav.startsWith('es')) return 'es';
    if (nav.startsWith('fr')) return 'fr';
  }
  return 'en';
}

interface I18nContextValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string) => string;
  locale: string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => readInitialLang());

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    setStoredLang(next);
  }, []);

  // Reflète la langue sur <html> + direction RTL pour l'arabe.
  useEffect(() => {
    if (typeof document === 'undefined') return;
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  }, [lang]);

  const value = useMemo<I18nContextValue>(() => {
    const dict = DICTS[lang];
    return {
      lang,
      setLang,
      // Fallback : clé manquante (surtout en 'ja') → anglais, puis français, puis la clé.
      t: (key) => dict[key] ?? DICTS.en[key] ?? DICTS.fr[key] ?? key,
      locale: LOCALES[lang],
    };
  }, [lang, setLang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within <I18nProvider>');
  return ctx;
}

export function useT(): (key: string) => string {
  return useI18n().t;
}
